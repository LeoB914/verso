// Build final JSON: commands with snippet + environment list separately.
const commands = []
const seen = new Set()
for (const [group] of groups) {
  for (const [name, args, description] of group) {
    const key = name + '|' + (args ?? '')
    if (seen.has(key)) continue
    seen.add(key)
    const label = args ? '\\' + name : '\\' + name
    commands.push({
      label,
      type: 'function',
      detail: description,
      apply: args ? '\\' + name + args : '\\' + name,
      snippet: Boolean(args && args.includes('${')),
    })
  }
}

